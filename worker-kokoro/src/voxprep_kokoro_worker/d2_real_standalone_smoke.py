"""D2 real-ONNX smoke for the independent async queue.

This script requires actual pinned Kokoro-82M files and FFmpeg.
It must not be used with fake synthesizers or dummy style arrays.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import tempfile
from dataclasses import replace
from pathlib import Path

from voxprep_kokoro_worker.adapters.voice_bundle import SUPPORTED_VOICES
from voxprep_kokoro_worker.application.durable_queue import DurableQueue
from voxprep_kokoro_worker.manifest_cli import create_manifest
from voxprep_kokoro_worker.standalone import StandaloneService, StandaloneSettings


def run(model_dir: Path, output_dir: Path, revision: str) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = create_manifest(model_dir, "kokoro-82m-d2", revision)
    with tempfile.TemporaryDirectory(prefix="kokoro-d2-") as temp:
        root = Path(temp)
        config_path = root / "manifest.json"
        config_path.write_text(json.dumps(manifest), encoding="utf-8")
        settings = StandaloneSettings(
            token="d2-smoke-local-only-token-unique-123456", host="127.0.0.1", port=0,
            manifest_path=config_path, cache_dir=root / "cache",
            temp_dir=root / "temp", output_dir=output_dir,
            local_model_dir=model_dir, hf_repo=None, model_s3_bucket=None,
            model_s3_prefix="", output_s3_bucket=None, output_s3_prefix="",
            s3_endpoint_url=None, s3_region=None,
        )
        service = StandaloneService(settings)
        service.startup()
        queue = DurableQueue(output_dir / "queue", service)
        evidence = []
        try:
            for code in SUPPORTED_VOICES:
                payload = {
                    "text": "Welcome to your English practice lesson. This audio was generated by Kokoro.",
                    "voiceCode": code, "speed": 1.0,
                }
                item, created = queue.submit(payload, "d2-" + code)
                assert created and item["status"] == "QUEUED"
                assert queue.process_once(), code
                result = queue.get(item["id"])
                if result["status"] != "SUCCEEDED":
                    raise AssertionError("Real Kokoro job failed: " + code)
                info = result["result"]
                file = output_dir / (item["id"] + ".mp3")
                assert file.is_file()
                with file.open("rb") as stream:
                    observed = hashlib.file_digest(stream, "sha256").hexdigest()
                assert observed == info["sha256"] and file.stat().st_size == info["sizeBytes"]
                assert info["durationMs"] > 0
                assert service.find(item["id"]) == info
                evidence.append({
                    "voiceCode": code, "jobId": item["id"], "sha256": observed,
                    "sizeBytes": file.stat().st_size, "durationMs": info["durationMs"],
                    "manifestSha256": manifest["manifestSha256"],
                })
        finally:
            queue.stop()
        # Durable persisted metadata and MP3 reopen without model/inference.
        restarted = DurableQueue(output_dir / "queue", service)
        try:
            for item in evidence:
                assert restarted.get(item["jobId"])["status"] == "SUCCEEDED"
                assert service.find(item["jobId"])["sha256"] == item["sha256"]
        finally:
            restarted.stop()
        report = {
            "engine": "KOKORO", "mode": "STANDALONE_D2_REAL",
            "manifestSha256": manifest["manifestSha256"], "jobs": evidence,
            "accepted": len(evidence) == 3,
            "limitations": ["Local S3/RustFS output not exercised", "Audio listening review required"],
        }
        (output_dir / "d2-real-smoke-evidence.json").write_text(
            json.dumps(report, indent=2), encoding="utf-8")
        return report


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-dir", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--revision", required=True)
    args = parser.parse_args()
    print(json.dumps(run(args.model_dir, args.output_dir, args.revision), indent=2))


if __name__ == "__main__":
    main()
