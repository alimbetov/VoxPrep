from __future__ import annotations
from pathlib import Path
from contextlib import AbstractContextManager
from typing import Protocol
from voxprep_kokoro_worker.domain.job import ClaimedJob, AudioArtifact

class BackendPort(Protocol):
    def claim(self, worker_id: str) -> ClaimedJob | None: ...
    def heartbeat(self, *, worker_id: str, job: ClaimedJob) -> None: ...
    def fail(self, *, worker_id: str, job: ClaimedJob, error_code: str, error_message: str) -> None: ...
    def upload_output(self, *, worker_id: str, job: ClaimedJob, artifact: AudioArtifact) -> None: ...

class ModelSourcePort(Protocol):
    def fetch_manifest(self, model_code: str) -> dict: ...
    def download_artifact(self, *, model_code: str, asset_id: str, destination: Path, max_bytes: int) -> None: ...

class ModelCachePort(Protocol):
    def ensure_model(self, job: ClaimedJob) -> Path: ...
    def hold_model(self, job: ClaimedJob) -> AbstractContextManager[Path]: ...
