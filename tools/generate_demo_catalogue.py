#!/usr/bin/env python3
"""Deterministic DEV/TEST-only Flutter and Backend mock catalogue generator.

python tools/generate_demo_catalogue.py [--seed 2026] [--count 32] [--check]
Never writes to DB, calls a Store, or runs in production.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FLUTTER = ROOT / "mobile/careerspeak_app/lib/data/mock/generated_demo_content.dart"
BACKEND = ROOT / "backend/src/test/resources/fixtures/demo_catalogue_seed.json"

BASE = [
    ("JAVA_DI_001", "interview", "Dependency Injection", "Java Backend", "B2"),
    ("JAVA_CONCURRENCY_001", "interview", "ConcurrentHashMap", "Java Backend", "C1"),
    ("VOCAB_SIGNIFICANT", "vocabulary", "significant", "Vocabulary", "B2"),
    ("VOCAB_SUBSTANTIAL", "vocabulary", "substantial", "Vocabulary", "C1"),
    ("IELTS_ENV_001", "topic", "Urban Environment", "IELTS", "B2"),
    ("SHADOW_SYSTEM_DESIGN_001", "shadowing", "Explaining System Design", "Professional English", "C1"),
    ("PHRASE_CLARIFY_001", "phrase", "Could you clarify the requirement?", "Phrase Bank", "B1"),
]
TOPICS = [
    ("JAVA", "Java Backend", "interview", "Explaining transaction boundaries"),
    ("JAVA", "Java Backend", "topic", "Spring Boot service design"),
    ("JAVA", "Java Backend", "shadowing", "Explaining microservice tradeoffs"),
    ("CLOUD", "Cloud and DevOps", "interview", "Describing deployment strategies"),
    ("CLOUD", "Cloud and DevOps", "topic", "Kubernetes rollout basics"),
    ("IELTS", "IELTS", "topic", "Education and Technology"),
    ("IELTS", "IELTS", "interview", "Giving a structured opinion"),
    ("BANKING", "Banking English", "interview", "Handling a customer inquiry"),
    ("BANKING", "Banking English", "topic", "Explaining a financial product"),
    ("MEDICAL", "Medical English", "phrase", "Could you describe your symptoms?"),
    ("MEDICAL", "Medical English", "topic", "Structured patient handover"),
    ("GENERAL", "Professional English", "vocabulary", "collaborative"),
]

def build(seed, count):
    if count < len(BASE) or count > 200:
        raise ValueError("count must be 7..200")
    records = []
    for code, kind, title, category, level in BASE:
        records.append(dict(code=code, type=kind, title=title, category=category,
                            level=level, minutes=5))
    for i in range(count - len(BASE)):
        vertical, category, kind, title = TOPICS[i % len(TOPICS)]
        batch = i // len(TOPICS) + 1
        records.append(dict(
            code=f"DEMO_{vertical}_{i+1:04d}", type=kind,
            title=title if batch == 1 else f"{title} - practice {batch}",
            category=category, level=["B1", "B2", "C1"][(seed + i) % 3],
            minutes=3 + (seed + 7 * i) % 10,
        ))
    categories = set()
    for record in records:
        record["accessLevel"] = "FREE" if record["category"] not in categories else "FULL"
        categories.add(record["category"])
        record["subtitle"] = f"{record['category']} - demo learning material"
        record["description"] = f"Practice English: {record['title']}."
    return dict(schemaVersion=1, fixture="voxprep-dev-test",
                seed=seed, productId="voxprep_full_unlock", items=records)

def escape(value):
    return value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")

def flutter_source(data):
    lines = [
        "// GENERATED by tools/generate_demo_catalogue.py - DO NOT EDIT.",
        "// DEV/TEST only. This source cannot grant backend FULL entitlement.",
        "import '../../domain/content_item.dart';",
        "",
        "const generatedDemoContentItems = <ContentItem>[",
    ]
    for item in data["items"]:
        lines.extend([
            "  ContentItem(",
            f"    code: '{escape(item['code'])}',",
            f"    type: ContentType.{item['type']},",
            f"    title: '{escape(item['title'])}',",
            f"    subtitle: '{escape(item['subtitle'])}',",
            *( [f"    description: '{escape(item['description'])}',"]
               if len(f"    description: '{escape(item['description'])}',") <= 80
               else ["    description:", f"        '{escape(item['description'])}',"] ),
            f"    category: '{escape(item['category'])}',",
            f"    level: '{escape(item['level'])}',",
            f"    minutes: {item['minutes']},",
            "    hasAudio: false,",
            "  ),",
        ])
    return "\n".join(lines + ["];"]) + "\n"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--count", type=int, default=32)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = build(args.seed, args.count)
    outputs = {
        FLUTTER: flutter_source(data),
        BACKEND: json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n",
    }
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, expected in outputs.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != expected]
        if stale:
            parser.error("stale generated fixtures: " + ", ".join(stale))
        print("OK: synchronized backend + Flutter demo fixtures")
        return
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print("Generated:", path.relative_to(ROOT))

if __name__ == "__main__":
    main()
