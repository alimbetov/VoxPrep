#!/usr/bin/env python3
"""Fail-closed R1 correlation of PostgreSQL CURRENT, HTTP root and offline Drift.

Inputs are generated by one real A1 run, not hand-written fixtures. This script
does not accept or emit credentials, installation tokens, or private content.
"""
import csv
import json
import sys
from pathlib import Path


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def sections(path):
    chunks = {}
    name = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("evidence_"):
            name = line.strip()
            chunks[name] = []
        elif name is not None and line.strip() and not line.startswith("("):
            chunks[name].append(line)
    return {
        name: list(csv.DictReader(lines))
        for name, lines in chunks.items()
    }


directory = Path(sys.argv[1])
database = sections(directory / "postgres-publication-snapshot.txt")
http = json.loads((directory / "http-root-n2.json").read_text(encoding="utf-8"))
flutter = json.loads((directory / "flutter-drift-evidence.json").read_text(encoding="utf-8"))

current = database.get("evidence_publication_current", [])
history = database.get("evidence_release_history", [])
refs = database.get("evidence_approved_exact_content_refs", [])
wire = database.get("evidence_immutable_wire_snapshots", [])
require(len(current) == 1, "Exactly one PostgreSQL CURRENT is required")
require(len(history) >= 2, "N and N+1 must both be committed to PostgreSQL")
require(bool(refs) and bool(wire), "Published refs and immutable wire rows are required")
require(all(row["checksum_matches"] == "t" for row in refs),
        "PostgreSQL revision mismatch in publication manifest")

live = current[0]
n2_version = int(http["contentVersion"])
require(int(live["content_version"]) == n2_version,
        "PostgreSQL CURRENT does not match HTTP N+1")
# publication_release.root_sha256 is the legacy candidate-ref digest.
# The learner HTTP root uses the immutable ROOT wire document checksum.
root_wire = [row for row in wire
             if row["document_kind"] == "ROOT"
             and int(row["content_version"]) == n2_version]
require(len(root_wire) == 1, "Exactly one frozen ROOT wire document is required")
require(root_wire[0]["checksum_sha256"] == http["checksum"],
        "PostgreSQL immutable ROOT wire checksum does not match HTTP root")
require(flutter["offlineCurrent"]["contentVersion"] == n2_version,
        "Offline Drift CURRENT does not match PostgreSQL CURRENT")
require(flutter["offlineCurrent"]["contentCode"] == "A1_FREE_PHRASE",
        "Unexpected offline content code")
require(flutter["offlineCurrent"]["revision"] == 2,
        "Offline Drift did not retain revision 2")
require(flutter["offlineCurrent"]["phrase"] ==
        "Could you introduce yourself professionally?",
        "Offline Drift typed body was not retained")
require(flutter["rootN"]["contentVersion"] == n2_version - 1,
        "N-to-N+1 sequence is invalid")
require(flutter["failureInjection"] == {
    "missingPayloadRejected": True,
    "checksumMismatchRejected": True,
    "preservedN": True,
}, "Fault injection invariants were not recorded")
require(http["contentPayload"]["code"] == "A1_FREE_PHRASE"
        and http["contentPayload"]["revision"] == 2,
        "HTTP content payload identity/revision mismatch")
require(any(row["content_code"] == http["contentPayload"]["code"]
            and int(row["revision_number"]) == http["contentPayload"]["revision"]
            and row["checksum_sha256"] == http["contentPayload"]["checksum"]
            and int(row["content_version"]) == n2_version for row in refs),
        "PostgreSQL exact revision SHA does not match HTTP content payload SHA")
require(len(flutter["offlineCurrent"]["freeCollectionMembers"]) ==
        len(set(flutter["offlineCurrent"]["freeCollectionMembers"])),
        "Offline Drift contains duplicate collection members")
require(len(http["packs"]) == 2, "Unexpected published HTTP pack count")
require(len({pack["code"] for pack in http["packs"]}) == 2,
        "HTTP root contains duplicate pack code")
require(any(int(row["content_version"]) == n2_version
            for row in wire), "N+1 immutable HTTP wire documents are missing")

report = {
    "verification": "PASS",
    "source": "live PostgreSQL + published HTTP root + reopened Flutter Drift",
    "nVersion": flutter["rootN"]["contentVersion"],
    "nPlusOneVersion": n2_version,
    "candidateRefSha256": live["root_sha256"],
    "httpWireRootSha256": root_wire[0]["checksum_sha256"],
    "httpContentPayloadSha256": http["contentPayload"]["checksum"],
    "currentReleaseId": live["current_release_id"],
    "databaseRevisionRefCount": len(refs),
    "immutableWireDocumentCount": len(wire),
    "offlineFreeMemberCount": len(flutter["offlineCurrent"]["freeCollectionMembers"]),
}
(directory / "r1-verified.json").write_text(
    json.dumps(report, sort_keys=True, indent=2) + "\n",
    encoding="utf-8",
)
print("R1_EVIDENCE_VERIFIED", n2_version, root_wire[0]["checksum_sha256"])
